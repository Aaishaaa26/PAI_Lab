import numpy as np

data = np.array([12.5, np.nan, 7.8, 15.2, np.nan, 9.1, 11.4, np.nan, 14.0, 6.3])
print("Original array:", data)
nan_mask = np.isnan(data)
print("NaN mask:", nan_mask)
print("NaN count:", nan_mask.sum())
print("NaN positions:", np.where(nan_mask)[0])
print("nanmean:", round(np.nanmean(data), 4))
print("nanmedian:", round(np.nanmedian(data), 4))
print("nanstd:", round(np.nanstd(data), 4))
print("nanmin:", np.nanmin(data))
print("nanmax:", np.nanmax(data))
print("nansum:", round(np.nansum(data), 4))
fill_value = np.nanmean(data)
cleaned = np.where(np.isnan(data), fill_value, data)
print("Cleaned array:", np.round(cleaned, 4))
print("Any NaN remaining:", np.isnan(cleaned).any())
print("Verification passed:", not np.isnan(cleaned).any())